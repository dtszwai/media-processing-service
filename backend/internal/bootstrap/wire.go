// Package bootstrap wires AWS clients, drivers, and app-layer repos. It is
// the single assembly root: every cmd binary calls Wire and consumes the
// assembled fields rather than constructing repos itself.
//
// Wire self-provisions local resources when no Terraform-managed topology is
// present. When Terraform injects resource ARNs/URLs through environment
// variables, those values are treated as authoritative and no resources are
// re-ensured.
